// The design carried inside the exported file (compile/embed.ts, learnings 1.19).
//
// *2026-11-11.* Jared, asked where a template's editable design should live when he works from Claude: "Inside the
// HubSpot file."
//
// Defended: the embed is opt-in and changes nothing else about the file; it sits after the generated-by comment, so
// the annotation still opens the file; it reads back as the exact saved template plus the system it compiled with,
// and recompiling that reproduces the file byte for byte; it carries no `#}`, `{{`, `{%` or `<`, however hostile the
// text in the design; the checks and the packager see through it; and the Gmail size leaves it out.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import { compile } from '../src/compile/compile.ts';
import { commentSafe, DESIGN_FORMAT, DESIGN_MARK, designComment, readDesign, withoutDesign } from '../src/compile/embed.ts';
import { errorsIn, lint } from '../src/compile/lint.ts';
import { completeDesignSystem, type DesignSystem } from '../src/model/design-system.ts';
import { materialiseFolderSystem } from '../src/model/edit.ts';
import { localSources, planPackage } from '../src/model/export-package.ts';
import { migrate } from '../src/model/schema.ts';
import { serializeTemplate } from '../src/model/serialize.ts';
import type { Template } from '../src/model/types.ts';

const at = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const systems: Record<string, DesignSystem> = {
  switchyards: completeDesignSystem(JSON.parse(readFileSync(at('design-systems/switchyards.system.json'), 'utf8'))),
  card: completeDesignSystem(JSON.parse(readFileSync(at('design-systems/card.system.json'), 'utf8'))),
};
/** A template as the app holds it once open: its folder system materialised. */
const opened = (file: string): Template => materialiseFolderSystem(migrate(JSON.parse(readFileSync(at(`templates/${file}`), 'utf8'))), systems).template;
const FIXTURES = ['standard-email.template.json', 'card-email.template.json', 'baseline.template.json'];

const date = '2026-11-11';
const plain = (t: Template) => compile(t, { mode: 'hubl', date });
const embedded = (t: Template) => compile(t, { mode: 'hubl', date, embedDesign: true, by: '0.10.0' });

/** What a reader does with the comment: the template back, its system put on it, recompiled. */
function reopen(source: string): { template: Template; ds: DesignSystem | undefined; by: string | null } {
  const read = readDesign(source);
  if (!read || !read.ok) throw new Error(read ? read.reason : 'no design');
  const ds = read.design.ds ? completeDesignSystem(read.design.ds) : undefined;
  return { template: migrate(read.design.template), ds, by: read.design.by };
}

describe('the embedded design', () => {
  it('is opt-in, and off it leaves the file exactly as it was', () => {
    for (const file of FIXTURES) {
      const t = opened(file);
      expect(plain(t).html).not.toContain(DESIGN_MARK);
      expect(compile(t, { mode: 'hubl', date, embedDesign: false }).html).toBe(plain(t).html);
    }
  });

  it('never reaches a preview', () => {
    const t = opened(FIXTURES[0]!);
    expect(compile(t, { mode: 'preview', embedDesign: true }).html).not.toContain(DESIGN_MARK);
  });

  it('adds one comment after the generated-by line and nothing else', () => {
    for (const file of FIXTURES) {
      const t = opened(file);
      const on = embedded(t).html;
      expect(on.startsWith('<!--')).toBe(true);
      expect(on.indexOf(`{# ${DESIGN_MARK} ${DESIGN_FORMAT}`)).toBeGreaterThan(on.indexOf('{# Generated by Template Studio'));
      expect(on.indexOf(`{# ${DESIGN_MARK}`)).toBeLessThan(on.indexOf('<!DOCTYPE'));
      expect(withoutDesign(on)).toBe(plain(t).html);
    }
  });

  it('reads back as the saved template and the system it compiled with', () => {
    for (const file of FIXTURES) {
      const t = opened(file);
      const back = reopen(embedded(t).html);
      expect(serializeTemplate(back.template)).toBe(serializeTemplate(t));
      expect(back.by).toBe('0.10.0');
      if (t.designSystem) expect(back.ds).toEqual(t.ds);
    }
  });

  it('recompiles to the same file, byte for byte', () => {
    for (const file of FIXTURES) {
      const t = opened(file);
      const source = embedded(t).html;
      const back = reopen(source);
      const again = compile(back.template, { mode: 'hubl', date, embedDesign: true, by: '0.10.0', ...(back.ds ? { ds: back.ds } : {}) });
      expect(withoutDesign(again.html)).toBe(withoutDesign(source));
    }
  });

  it('keeps a folder-backed template whole: the card system travels with the card email', () => {
    const t = opened('card-email.template.json');
    expect(t.designSystem).toBe('card');
    const read = readDesign(embedded(t).html);
    expect(read && read.ok && read.design.system).toBe('card');
    expect(read && read.ok && read.design.ds).toBeTruthy();
    // The saved file alone compiles against the defaults, which is why the system has to come along.
    const fileAlone = migrate(JSON.parse(serializeTemplate(t)));
    expect(plain(fileAlone).html).not.toBe(plain(t).html);
  });

  it('holds nothing HubL, HubSpot or the checks could read as their own', () => {
    const t = opened(FIXTURES[2]!);
    const hostile = structuredClone(t);
    hostile.name = 'Ends #} early {{ contact.firstname }} {% if x %} <p>100% & more</p> {# not a comment';
    hostile.previewText = '#}#}{%%}{{}}';
    const comment = /\{# template-studio:design[\s\S]*?#\}/.exec(embedded(hostile).html)?.[0] ?? '';
    const payload = comment.slice(2, -2);
    for (const bad of ['#}', '{{', '{%', '{#', '%}', '<', '>', '&']) expect(payload).not.toContain(bad);
    expect(reopen(embedded(hostile).html).template.name).toBe(hostile.name);
  });

  it('escapes only inside strings, so the JSON reads back identically', () => {
    const value = { a: '<p>#}{{x}}%</p>', 'k{#}': [1, { b: 'a\\"q"}' }], c: null };
    const safe = commentSafe(JSON.stringify(value));
    expect(JSON.parse(safe)).toEqual(value);
    expect(safe).not.toMatch(/[<>&%#]|\{\{|\{%|#\}/);
  });

  it('passes the checks, and leaves the size Gmail sees alone', () => {
    for (const file of FIXTURES) {
      const t = opened(file);
      const on = embedded(t);
      expect(errorsIn(lint({ ...on, mode: 'hubl', template: t }))).toEqual([]);
      expect(on.bytes).toBe(plain(t).bytes);
      expect(new TextEncoder().encode(on.html).length).toBeGreaterThan(on.bytes);
    }
  });

  it('is invisible to the packager, which leaves it as it was', () => {
    const t = structuredClone(opened(FIXTURES[2]!));
    const image = t.sections.flatMap((s) => s.rows.flatMap((r) => r.columns.flatMap((c) => c.blocks))).find((b) => b.type === 'image');
    if (!image || image.type !== 'image') throw new Error('baseline has an image');
    image.src = 'photos/hero.png';
    const source = embedded(t).html;
    expect(localSources(source)).toEqual(localSources(plain(t).html));
    const packed = planPackage(source);
    expect(packed.pictures.map((p) => p.src)).toContain('photos/hero.png');
    const before = readDesign(source);
    const after = readDesign(packed.html);
    expect(after).toEqual(before);
  });

  it('says why when it cannot read one', () => {
    expect(readDesign('<html></html>')).toBeNull();
    const newer = `{# ${DESIGN_MARK} ${DESIGN_FORMAT + 1}\n{"template":{}}\n#}`;
    expect(readDesign(newer)).toMatchObject({ ok: false });
    const edited = `{# ${DESIGN_MARK} ${DESIGN_FORMAT}\n{"template": {broken\n#}`;
    expect(readDesign(edited)).toMatchObject({ ok: false });
    const crlf = designComment(opened(FIXTURES[0]!), systems['switchyards']!).replace(/\n/g, '\r\n');
    expect(readDesign(crlf)).toMatchObject({ ok: true });
  });
});
